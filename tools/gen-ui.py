#!/usr/bin/env python3
"""Make src/ui_assets.h: the font and icons of the status screens (src/screen.c), from assets/.

Glyphs (8-bit coverage) and icons (RGBA) are run-length encoded: a count byte (1..255), then one value
(1 byte for glyphs, 4 for icons).

Any TrueType/OpenType font works: the one .ttf/.otf in assets/ or the one given. Glyphs are drawn from the
outlines (embedded bitmap strikes are dropped), kerning is measured pair by pair with the font's own layout
(HarfBuzz through Pillow's raqm: 'kern' table and GPOS alike).
Needs Pillow (with raqm for kerning), fontTools and numpy, so the header is kept in git and the build does not run
this: run it after changing anything in assets/.

    python3 tools/gen-ui.py [FONT]
"""
import glob
import io
import os
import sys

import numpy as np
from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont, features

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
ASSETS = os.path.join(ROOT, "assets")
OUT = os.path.join(ROOT, "src", "ui_assets.h")
if len(sys.argv) > 1:
    FONT = sys.argv[1]
else:
    found = sorted(glob.glob(os.path.join(ASSETS, "*.ttf")) + glob.glob(os.path.join(ASSETS, "*.otf")))
    if len(found) != 1:
        sys.exit("assets/ must hold exactly one .ttf/.otf font (or give one): %s" % found)
    FONT = found[0]
FONTS = {"TITLE": 72, "TEXT": 36, "SMALL": 28}
FIRST, LAST = 32, 126

out = ["/* generated by tools/gen-ui.py from assets/: do not edit */",
       "typedef struct { const unsigned char *rle; short w, h, x, y, adv; } UiGlyph;",
       "typedef struct { short size, ascent, descent; UiGlyph g[%d]; const signed char (*kern)[3]; short nkern; } UiFont;"
       % (LAST - FIRST + 1),
       "typedef struct { const unsigned char *rle; short w, h; } UiIcon;",
       "#define UI_FIRST %d" % FIRST, "#define UI_LAST %d" % LAST]
total = 0


def rle(values, size):
    """values: a list of tuples (size bytes each)"""
    b, i = [], 0
    while i < len(values):
        n = 1
        while i + n < len(values) and n < 255 and values[i + n] == values[i]:
            n += 1
        b.append(n)
        b.extend(values[i])
        i += n
    return b


def array(name, data):
    global total
    total += len(data)
    rows = [",".join(str(x) for x in data[i:i + 32]) for i in range(0, len(data), 32)]
    out.append("static const unsigned char %s[%d] = {\n%s};" % (name, len(data), ",\n".join(rows)))


# outlines only: FreeType would use an embedded bitmap strike at its exact size
tt = TTFont(FONT)
if "glyf" in tt or "CFF " in tt or "CFF2" in tt:
    for t in ("EBDT", "EBLC", "EBSC", "CBDT", "CBLC", "sbix", "bdat", "bloc"):
        if t in tt:
            del tt[t]
buf = io.BytesIO()
tt.save(buf)
FONT_DATA = buf.getvalue()
RAQM = features.check("raqm")
if not RAQM:
    print("warning: Pillow without raqm, no kerning", file=sys.stderr)
print("font:", os.path.basename(FONT), tt["name"].getDebugName(4))

for fname, size in FONTS.items():
    font = ImageFont.truetype(io.BytesIO(FONT_DATA), size)
    lay = ImageFont.truetype(io.BytesIO(FONT_DATA), size, layout_engine=ImageFont.Layout.RAQM) if RAQM else None
    ascent, descent = font.getmetrics()
    glyphs = []
    for c in range(FIRST, LAST + 1):
        ch = chr(c)
        adv = round(font.getlength(ch))
        box = font.getbbox(ch, anchor="ls")
        w, h = box[2] - box[0], box[3] - box[1]
        name = "font_%s_%d" % (fname.lower(), c)
        if w <= 0 or h <= 0:
            glyphs.append("{0, 0, 0, 0, 0, %d}" % adv)
            continue
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-box[0], -box[1]), ch, fill=255, font=font, anchor="ls")
        array(name, rle([(v,) for v in img.tobytes()], 1))
        glyphs.append("{%s, %d, %d, %d, %d, %d}" % (name, w, h, box[0], box[1], adv))
    kern = []
    if lay:   # a pair's width minus its glyphs' widths, with ligatures off
        nolig = ["-liga", "-clig", "-dlig"]
        w1 = {c: lay.getlength(chr(c), features=nolig) for c in range(FIRST, LAST + 1)}
        for a in range(FIRST, LAST + 1):
            for b in range(FIRST, LAST + 1):
                k = round(lay.getlength(chr(a) + chr(b), features=nolig) - w1[a] - w1[b])
                if k:
                    kern.append((a, b, max(-128, min(127, k))))
    kname = "NULL"
    if kern:
        kname = "kern_%s" % fname.lower()
        out.append("static const signed char %s[%d][3] = {%s};"
                   % (kname, len(kern), ",".join("{%d,%d,%d}" % k for k in kern)))
    out.append("static const UiFont UI_FONT_%s = {%d, %d, %d, {\n    %s},\n    %s, %d};"
               % (fname, size, ascent, descent, ",\n    ".join(glyphs), kname, len(kern)))


def icon(name, img):
    img = img.convert("RGBA")
    b = img.tobytes()
    array("icon_" + name, rle([tuple(b[i:i + 4]) for i in range(0, len(b), 4)], 4))
    out.append("static const UiIcon UI_ICON_%s = {icon_%s, %d, %d};" % (name.upper(), name, img.width, img.height))


def load(name, scale=1.0):
    img = Image.open(os.path.join(ASSETS, name + ".png")).convert("RGBA")
    if scale != 1.0:
        img = img.resize((round(img.width * scale), round(img.height * scale)), Image.LANCZOS)
    return img


def ring(size, radius, width, rgb):
    """a circle outline (radius to the middle of the line), drawn 4x larger and scaled down for smooth edges"""
    k = 4
    img = Image.new("RGBA", (size * k, size * k), rgb + (0,))
    c, r = size * k / 2, (radius + width / 2) * k
    ImageDraw.Draw(img).ellipse((c - r, c - r, c + r - 1, c + r - 1), outline=rgb + (255,), width=width * k)
    return img.resize((size, size), Image.LANCZOS)


def arc_geometry(frames):
    """radius and line width of the loader's arc: what moves between the frames (the per-pixel minimum over
    all frames is the still background, the maximum is background plus arc)"""
    al = np.array([np.asarray(f.getchannel("A"), dtype=float) for f in frames])
    lo, hi = al.min(axis=0), al.max(axis=0)
    cov = np.clip((hi - lo) / np.maximum(1.0, 255 - lo), 0, 1)
    h, w = hi.shape
    y, x = np.mgrid[0:h, 0:w]
    r = np.hypot(x + 0.5 - w / 2, y + 0.5 - h / 2)
    radius = (cov * r).sum() / cov.sum()
    return radius, cov.sum() / (2 * np.pi * radius)


for g in ("glasses_grey", "glasses_white", "glasses_red"):
    icon(g, load(g, 2.5))
icon("step_done", load("ok_solid", 1.5))
icon("step_failed", load("warning_red", 2.0))
# the step being waited for: the loader animation (assets/loader/frame0.png, frame1.png, ...)
loader = []
while os.path.exists(os.path.join(ASSETS, "loader", "frame%d.png" % len(loader))):
    loader.append(Image.open(os.path.join(ASSETS, "loader", "frame%d.png" % len(loader))).convert("RGBA"))
for i, f in enumerate(loader):
    icon("loader%d" % i, f)
out.append("#define UI_LOADER_FRAMES %d" % len(loader))
out.append("static const UiIcon *const UI_LOADER[%d] = {%s};"
           % (len(loader), ", ".join("&UI_ICON_LOADER%d" % i for i in range(len(loader)))))
# steps still to come: an empty circle with the loader arc's radius and line width
radius, width = arc_geometry(loader)
print("loader: %d frames %dx%d, arc radius %.1f, width %.1f" % (len(loader), loader[0].width, loader[0].height, radius, width))
icon("step_pending", ring(loader[0].width, round(radius), round(width), (90, 90, 90)))
icon("warning_orange", load("warning_orange", 1.5))
icon("warning_red", load("warning_red", 1.5))
for n in range(4):
    icon("wifi%d" % n, load("wifi%d" % n))
off = load("wifi0")
# Wi-Fi failed: the empty-bars icon with the disc turned red
def to_red(img):
    import colorsys
    out = []
    px = img.tobytes()
    for k in range(0, len(px), 4):
        r, g, b, a = px[k:k + 4]
        h, s, v = colorsys.rgb_to_hsv(r / 255, g / 255, b / 255)
        if s > 0.3:
            r, g, b = (round(c * 255) for c in colorsys.hsv_to_rgb(0.993, s * 0.86, v))
        out.append((r, g, b, a))
    red = Image.new("RGBA", img.size)
    red.putdata(out)
    return red


icon("wifi_error", to_red(load("wifi0")))
icon("wifi_off", Image.merge("RGBA", (*[off.convert("L").point(lambda v: v * 0.45)] * 3, off.getchannel("A"))))
# Wi-Fi connecting: assets/wifi_0.png, wifi_1.png, ... (no bar lit, one, two, ...), played forth and back
search = []
while os.path.exists(os.path.join(ASSETS, "wifi_%d.png" % len(search))):
    search.append(load("wifi_%d" % len(search)))
for i, f in enumerate(search):
    icon("wifi_search%d" % i, f)
out.append("#define UI_WIFI_SEARCH_FRAMES %d" % len(search))
out.append("static const UiIcon *const UI_WIFI_SEARCH[%d] = {%s};"
           % (len(search), ", ".join("&UI_ICON_WIFI_SEARCH%d" % i for i in range(len(search)))))

with open(OUT, "w") as f:
    f.write("\n".join(out) + "\n")
print(OUT, total, "bytes of data")
