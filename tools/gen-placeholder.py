#!/usr/bin/env python3
"""Make src/placeholder_jpg.h: the JPEGs /snapshot serves while there is no picture from the goggles.

A black 1920x1080 frame with one message in the middle, in a bold italic sans like the goggles' own widgets.
Needs Pillow and the font (macOS: Avenir Next), so the header is kept in git and the build does not run this.

    python3 tools/gen-placeholder.py [FONT [INDEX]]
"""
import io
import os
import sys

from PIL import Image, ImageDraw, ImageFont

W, H = 1920, 1080
MESSAGES = {
    "PLACEHOLDER_NO_GOGGLES": "NO GOGGLES",
    "PLACEHOLDER_NO_VIDEO": "NO SIGNAL",
}
FONT = sys.argv[1] if len(sys.argv) > 1 else "/System/Library/Fonts/Avenir Next.ttc"
INDEX = int(sys.argv[2]) if len(sys.argv) > 2 else 1  # Avenir Next Bold Italic
OUT = os.path.join(os.path.dirname(__file__), "..", "src", "placeholder_jpg.h")


def jpeg(text):
    img = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(img)
    font = ImageFont.truetype(FONT, 40, index=INDEX)
    d.text((W / 2, H / 2), text, fill=255, font=font, anchor="mm")
    b = io.BytesIO()
    img.save(b, "JPEG", quality=85, optimize=True)
    return b.getvalue()


with open(OUT, "w") as f:
    f.write("/* generated by tools/gen-placeholder.py */\n")
    for name, text in MESSAGES.items():
        data = jpeg(text)
        f.write(f"/* \"{text}\" */\nstatic const unsigned char {name}[{len(data)}] = {{\n")
        for i in range(0, len(data), 24):
            f.write("    " + ",".join(str(x) for x in data[i:i + 24]) + ",\n")
        f.write("};\n")
        print(name, len(data), "bytes")
