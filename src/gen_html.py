#!/usr/bin/env python3
"""web/*.html -> C header with a string (embeds the pages into the binary)."""
import sys
src, name, dst = sys.argv[1], sys.argv[2], sys.argv[3]
data = open(src, encoding='utf-8').read()
lines = []
for ln in data.splitlines(True):
    esc = ln.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')
    lines.append('"' + esc + '"')
with open(dst, 'w') as f:
    f.write('/* generated by gen_html.py from %s — do not edit by hand */\n' % src)
    f.write('static const char %s[] =\n%s;\n' % (name, '\n'.join(lines)))
